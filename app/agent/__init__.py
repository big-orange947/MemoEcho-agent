# agent 包 - LangGraph 对话代理(系统的"大脑")
# -----------------------------------------------------------------------------
# 架构要点(请先读这里再读具体文件):
#
#   1. 单一图,六类节点:
#        ingest    -> 归一化事件、去重、写消息
#        retrieve  -> 拉历史 + 记忆 + 人设,组装 LLM 上下文
#        reason    -> LLM ReAct 决策: 回复 / 用工具 / 等待 / 完成
#        act       -> 执行 reason 选中的工具,结果回写
#        reflect   -> 判断目标是否达成、是否需要继续
#        finalize  -> 生成最终回复、落库、推送桌面端
#
#   2. 状态即会话: 每个会话在 LangGraph checkpoint 里有独立线程,
#      新事件进来 = 从 checkpoint 恢复 -> 再跑一次图 -> 存回 checkpoint。
#      这就是"事件驱动恢复",不再需要 v1 的 dispatch/lease/requeue。
#
#   3. 阅读顺序建议:
#        state.py   -> 先看"状态里有什么"
#        prompts.py -> 再看"LLM 被要求怎么思考"
#        graph.py   -> 然后看"节点怎么连成图"
#        nodes/     -> 最后逐个看节点做了什么
# =============================================================================
