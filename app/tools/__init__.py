# =============================================================================
# tools 包 - LangChain 工具集
# -----------------------------------------------------------------------------
# 工具是 agent 的"手脚": LLM 在 reason 节点自主决定是否调用、调用哪个。
# 每个工具用 @tool 装饰,自动生成 JSON schema 绑定给模型。
#
# 设计原则:
#   - 工具只做"动作",不做"决策"(决策永远在 LLM);
#   - 工具结果用自然语言文本返回,模型能直接理解;
#   - 与业务解耦: 工具内部调用 services 层或 bridge 层。
# =============================================================================
